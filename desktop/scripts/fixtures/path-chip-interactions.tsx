  await click('Open file docs/guide.md#L8');
  assert(calls.at(-1)?.path==='docs/guide.md' && calls.at(-1)?.line===8,'Markdown file link lost its location');
  await click('Open file /repo/src/app.ts:12:3');
  assert(JSON.stringify(calls.at(-1))===JSON.stringify({path:'src/app.ts',line:12,column:3}),'Wrong line or column');
